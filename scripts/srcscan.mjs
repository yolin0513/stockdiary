// 掃原始碼用的小工具。
//
// 只有一個函式，但它值得單獨一個檔案＋自己的對照組：稽核「程式碼裡有沒有 X」時，
// 註解裡的 X 不算數（不然等於罰人寫註解），而**網址裡的 `//` 也不是註解**。
// 這兩件事都踩過：
//   · shelltest 把 shell.js 註解裡的 `from '../app.js'` 當成真的 import
//   · workertest 的第一版把 `fetch('https://api.anthropic.com/…')` 的網址吃掉了
//     （`//api.anthropic.com/…` 被當成行註解），於是「該抓的沒抓到」

/**
 * 去掉 JS 註解，但**不要動到網址裡的 `//`**。
 * 判斷方式：`//` 前面緊接著 `:` 就是網址的一部分（`http://`、`https://`、`ws://`…）。
 *
 * 這不是完整的 JS 剖析器 —— 字串裡寫 `"/* "` 之類的還是會被誤判。
 * 對「稽核原始碼有沒有出現某個字串」這個用途夠用，而且寧可少剝也不要多剝。
 */
export function stripComments(source) {
  return source
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:])\/\/.*$/gm, '$1');
}
